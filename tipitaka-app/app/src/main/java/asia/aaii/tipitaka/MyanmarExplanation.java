    out.append("ဤရှင်းလင်းချက်သည် ပါဠိစာသားကို အစားထိုးသော တိုက်ရိုက်ဘာသာပြန်မဟုတ်ပါ။ စာပိုဒ်ထဲတွင် တွေ့ရသော အဓိကတရားဝေါဟာရများကို အခြေခံသည့် လေ့လာရေးအထောက်အကူဖြစ်သည်။\n\n");
    List<Concept> found=new ArrayList<>();
    String text=passage==null?"":passage;
    for(Concept c:CONCEPTS){
      for(String key:c.keys){
        if(text.contains(key)){found.add(c);break;}
      }
      if(found.size()>=4)break;
    }
    if(found.isEmpty()){
      out.append("အကြောင်းအရာကို နားလည်ရန် လမ်းညွှန်\n");
      if(category!=null&&category.contains("ဝိနည်း")){
        out.append("ဤဝိနည်းကျမ်းပိုဒ်ကို ဖတ်ရာတွင် (၁) ဖြစ်ပေါ်လာသည့် နောက်ခံအကြောင်း၊ (၂) သက်ဆိုင်သည့် ပုဂ္ဂိုလ်နှင့် အခြေအနေ၊ (၃) ချမှတ်ထားသော စည်းကမ်း၊ (၄) ခွင့်ပြုချက်နှင့် ခြွင်းချက်များကို ခွဲခြားလေ့လာပါ။ စည်းကမ်းတစ်ခုကို အခြားအခြေအနေသို့ တိုက်ရိုက်မချဲ့ထွင်ဘဲ မူရင်းဝိနည်းနောက်ခံနှင့် တွဲဖတ်ပါ။");
      }else if(category!=null&&category.contains("အဘိဓမ္မာ")){
        out.append("ဤအဘိဓမ္မာပိုဒ်ကို ဖတ်ရာတွင် (၁) ဖော်ပြထားသော တရားအမည်၊ (၂) အမျိုးအစားခွဲခြားပုံ၊ (၃) အခြားတရားများနှင့် ဆက်စပ်ပုံ၊ (၄) ဥပမာ သို့မဟုတ် မေးခွန်းပုံစံတို့ကို သီးခြားမှတ်သားပါ။ အဓိပ္ပါယ်မသေချာသော ပါဠိဝေါဟာရကို ခန့်မှန်း၍ ဘာသာမပြန်သင့်ပါ။");
      }else{
        out.append("ဤသုတ္တန်ပိုဒ်ကို ဖတ်ရာတွင် (၁) မည်သူက မည်သူ့အား ဟောကြားသည်၊ (၂) မေးခွန်း သို့မဟုတ် အခြေအနေက ဘာလဲ၊ (၃) အဓိကတရားအချက်က ဘာလဲ၊ (၄) အခြားသုတ်များတွင် အလားတူအယူအဆ ရှိသလားကို စဉ်းစားပါ။ ပါဠိစကားလုံးတိုင်း၏ အဓိပ္ပါယ်ကို စာပိုဒ်တစ်ပိုဒ်တည်းဖြင့် မဆုံးဖြတ်သင့်ပါ။");
      }
      out.append("\n\nလက်တွေ့လေ့လာရန်\nစာပိုဒ်ကို တစ်ကြိမ်ဖတ်ပြီး မသိသော ဝေါဟာရများကို မှတ်သားပါ။ ထို့နောက် ရှေ့နောက်စာပိုဒ်များနှင့် တွဲဖတ်ကာ အဓိကအယူအဆကို မိမိစကားဖြင့် အကျဉ်းချုပ်ရေးကြည့်ပါ။");
      out.append("\n\nဆင်ခြင်ရန်\nဤစာပိုဒ်က မည်သည့်ပြဿနာ၊ အယူအဆ သို့မဟုတ် လက်တွေ့ကျင့်စဉ်ကို နားလည်စေလိုသနည်း။");
    }else{
      out.append("တွေ့ရှိသော အဓိကတရားအယူအဆများ\n\n");
      for(Concept c:found){
        out.append("● ").append(c.name).append("\n");
        out.append("အဓိပ္ပါယ် — ").append(c.meaning).append("\n");
        out.append("ဆက်စပ်သဘော — ").append(c.context).append("\n");
        out.append("လက်တွေ့လေ့လာရန် — ").append(c.practice).append("\n");
        out.append("ဆင်ခြင်ရန် — ").append(c.reflect).append("\n\n");
      }
    }
    out.append("လေ့လာမှုမှတ်ချက် — ပါဠိဝေါဟာရများ၏ အနက်သည် ကျမ်းနောက်ခံနှင့် ရိုးရာအနက်ဖွင့်ပုံအလိုက် အသေးစိတ်ကွဲပြားနိုင်သည်။ ဤမှတ်စုကို အခြေခံလေ့လာရေးအဖြစ်သာ အသုံးပြုပြီး ဆရာတော်များ၏ ရှင်းလင်းချက်၊ အဋ္ဌကထာနှင့် ဘာသာပြန်ကျမ်းများဖြင့် ထပ်မံတိုက်ဆိုင်လေ့လာပါ။");
    return out.toString();
